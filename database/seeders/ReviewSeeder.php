    /**
     * Seed realistic visitor reviews for every place in the catalogue.
     */
    public function run(): void
    {
        $places = Place::query()->get(['id', 'category']);
        $placeIds = $places->pluck('id');

        Review::query()
            ->whereNull('user_id')
            ->whereIn('place_id', $placeIds)
            ->delete();

        $now = now();
        $rows = [];

        foreach ($places as $place) {
            $reviews = $this->reviews()[$place->category->value] ?? [];
            shuffle($reviews);

            foreach (array_slice($reviews, 0, $this->reviewCount()) as $content) {
                $rows[] = [
                    'place_id' => $place->id,
                    'user_id' => null,
                    'author' => self::AUTHORS[array_rand(self::AUTHORS)],
                    'rating' => $this->rating(),
                    'content' => $content,
                    'source' => 'visitor',
                    'reviewed_at' => $now->copy()->subDays(random_int(3, 360)),
                    'created_at' => $now,
                    'updated_at' => $now,
                ];
            }
        }

        Review::query()->insert($rows);
    }

    /**
     * The number of reviews to seed for a single place.
     */
    private function reviewCount(): int
    {
        $roll = random_int(1, 20);

        if ($roll <= 10) {
            return 2;
        }

        if ($roll <= 17) {
            return 3;
        }

        return 4;
    }

    /**
     * The rating to assign, weighted towards four and five stars.
     */
    private function rating(): int
    {
        $roll = random_int(1, 100);

        if ($roll <= 5) {
            return 3;
        }

        if ($roll <= 50) {
            return 4;
        }

        return 5;
    }

